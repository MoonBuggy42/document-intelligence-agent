from tools import generate_and_save_graph, generate_formatted_pdf_document
import numpy as np
import json
import os

# FIX: when calling LangChain @tool / StructuredTool objects directly from a script
# (not through an agent), always prefer the raw .func attribute.  All LangChain tools
# are callable, so checking `callable()` first always succeeds and the .func fallback
# (which skips wrapper overhead and input-schema validation) was never reached.
graph_fn = getattr(generate_and_save_graph, 'func', generate_and_save_graph)
pdf_fn   = getattr(generate_formatted_pdf_document, 'func', generate_formatted_pdf_document)

# Create a sample quantum-style plot (Gaussian wavepacket)
x = np.linspace(-10, 10, 400)
psi = np.exp(-x**2/8) * np.cos(2.0 * x)

series  = {'x': x.tolist(), 'y': psi.tolist(), 'name': 'Gaussian wavepacket'}
payload = {
    'data_json': [series],
    'title':     'Gaussian Wavepacket',
    'x_label':   'x',
    'y_label':   'Amplitude',
    'file_name': 'quantum_wave.png',
}

print('Generating graph...')
try:
    res = graph_fn(payload)
    print('Graph tool returned:', res)
except Exception as e:
    print('Graph invocation failed:', e)

img_path = os.path.join(os.path.dirname(__file__), 'quantum_wave.png')

# Build a simple HTML content including the graph and brief summary
content_html = '''<h1>Quantum Mechanics — Brief Summary</h1>
<p>Quantum mechanics is the fundamental theory describing nature at small scales. This report includes a sample visualization (Gaussian wavepacket) generated by the agent.</p>
<img src="%s" />
<h2>References</h2>
<ul>
<li>https://en.wikipedia.org/wiki/Quantum_mechanics</li>
<li>https://www.britannica.com/science/quantum-mechanics-physics</li>
</ul>
''' % img_path.replace('\\', '/')

pdf_name = 'quantum_report.pdf'
print('Generating PDF...')
try:
    pdf_res = pdf_fn(pdf_name, 'Quantum Mechanics', 'Quantum Mechanics', content_html)
    print('PDF tool returned:', pdf_res)
except Exception as e:
    print('PDF invocation failed:', e)

# Dump debug artifacts if available
for label, path in (('Last graph payload', 'last_graph_payload.json'),
                     ('Last pdf payload',   'last_pdf_payload.json')):
    try:
        with open(path, 'r', encoding='utf-8') as f:
            print(f'\n{label}:')
            print(f.read())
    except Exception:
        pass

print('\nDone.')